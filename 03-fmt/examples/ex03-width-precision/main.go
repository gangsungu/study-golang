// 너비(width), 플래그(0, -, +), 정밀도(precision)를 확인한다.
// 결과를 [ ]로 감싸서 공백이 어디에 들어갔는지 보이게 했다.
package main

import "fmt"

func main() {
	a, b := 123, 456
	c := 123456789

	fmt.Println("--- 정수: 너비와 플래그 ---")
	fmt.Printf("[%5d] [%5d]\n", a, b)    // 최소 너비 5, 오른쪽 정렬, 빈칸은 공백
	fmt.Printf("[%05d] [%05d]\n", a, b)  // 최소 너비 5, 오른쪽 정렬, 빈칸은 0
	fmt.Printf("[%-5d] [%-05d]\n", a, b) // 최소 너비 5, 왼쪽 정렬, 빈칸은 공백
	// %-05d 에서 0 플래그는 무시된다. 오른쪽에 0을 채우면 123이 12300 으로 읽혀 값이 달라지기 때문이다.
	fmt.Printf("[%+d] [%+d]\n", a, -b) // 양수에도 부호를 붙임

	fmt.Println("--- 너비보다 값이 길면 ---")
	fmt.Printf("[%5d] [%05d] [%-5d]\n", c, c, c) // 자르지 않고 그대로 출력

	fmt.Println("--- 실수: 정밀도 ---")
	f := 324.13455
	fmt.Printf("[%f]\n", 3.14)              // 정밀도 생략 시 소수점 이하 6자리
	fmt.Printf("[%.2f]\n", f)               // 소수점 이하 2자리
	fmt.Printf("[%8.2f]\n", f)              // 전체 너비 8 (소수점 포함), 소수점 이하 2자리
	fmt.Printf("[%08.2f]\n", f)             // 위와 같고 빈칸은 0
	fmt.Printf("[%8.5g]\n", f)              // %g의 정밀도는 "유효숫자 개수" -> 324.13
	fmt.Printf("[%08.2g]\n", f)             // 유효숫자 2개로는 324를 못 나타내서 지수 표기로 바뀜
	fmt.Printf("[%.0f] [%.0f]\n", 2.5, 3.5) // 반올림은 짝수 쪽으로 (2, 4). 자바는 3, 4

	fmt.Println("--- 문자열 ---")
	fmt.Printf("[%5s] [%-5s]\n", "go", "go") // 문자열도 너비·정렬이 같음
	fmt.Printf("[%.2s]\n", "golang")         // 문자열에서 정밀도는 "최대 글자 수"
	fmt.Printf("[%5s]\n", "한글")              // 너비는 바이트가 아니라 rune 수 기준. 화면 폭과는 다를 수 있음

	fmt.Println("--- 너비를 인자로 넘기기 ---")
	fmt.Printf("[%*d]\n", 7, a) // * 자리에 인자 7이 들어감
}
